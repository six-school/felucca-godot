"""Per-copy renames of the firmware's globals (docs/DESIGN.md D3): N copies of core/board.c link into one binary only
if every global symbol one defines has a name of its own. The list comes from `nm` of a reference build, not by hand,
so a Felucca update that adds a global is renamed too; the check catches what the list missed (the linker would not
always: tentative definitions with -fcommon, and weak symbols, merge silently).

    renames.py list OBJ          the globals OBJ defines, one a line, but the entry point (fel_core_<n>)
    renames.py header N LIST     a header for copy N: #define name fel<N>_name for each (force-included: -include)
    renames.py check N OBJ       every global copy N defines is fel<N>_* or fel_core_<N>; else names the rest, exit 1

NM (env) is the nm to run (default: nm). ELF/Linux so far (DESIGN.md §13.5: Mach-O adds a leading _, COFF later).
"""
import os, re, subprocess, sys

ENTRY = re.compile(r"fel_core_\d+$")


def defined_globals(obj):
    """(name, type) of every global symbol obj defines: nm -P lines are `name type [value size]`; U is undefined, w and
    v weak undefined. C (common) and W / V (weak) are definitions the linker may merge without a word."""
    out = subprocess.run([os.environ.get("NM", "nm"), "-P", "-g", obj], check=True, capture_output=True, text=True)
    syms = []
    for line in out.stdout.splitlines():
        f = line.split()
        if len(f) >= 2 and f[1] not in ("U", "w", "v"):
            syms.append((f[0], f[1]))
    return syms


def main(argv):
    if len(argv) == 3 and argv[1] == "list":
        names = sorted({n for n, _ in defined_globals(argv[2]) if not ENTRY.match(n)})
        sys.stdout.write("".join(n + "\n" for n in names))
    elif len(argv) == 4 and argv[1] == "header":
        n = int(argv[2])
        names = [s for s in open(argv[3]).read().split() if s]
        sys.stdout.write(f"/* generated by core/renames.py: copy {n} of the firmware, its globals renamed (D3) */\n")
        sys.stdout.write("".join(f"#define {s} fel{n}_{s}\n" for s in names))
    elif len(argv) == 4 and argv[1] == "check":
        n = int(argv[2])
        bad = [f"{s} ({t})" for s, t in defined_globals(argv[3]) if not (s.startswith(f"fel{n}_") or s == f"fel_core_{n}")]
        if bad:
            sys.stderr.write(f"{argv[3]}: copy {n} defines globals without its prefix fel{n}_: {', '.join(bad)}\n")
            return 1
    else:
        sys.stderr.write(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
